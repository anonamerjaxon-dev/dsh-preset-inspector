#!/usr/bin/env node
/**
 * build.mjs — writes lib/client.js from ui.js.
 *
 * The Web UI loads a plugin's browser half through `window.__ModuleLoader__`,
 * which is a plain, already-bundled module wrapper — no bundler, no build
 * toolchain, no npm dependency. This script is the whole "build": it takes the
 * two strings in ui.js and emits that wrapper, so ui.js stays the single source
 * of truth and the shipped file stays readable.
 *
 *   node build.mjs      # regenerate lib/client.js
 *   node build.mjs --check   # fail if lib/client.js is stale
 */

import fs from 'node:fs'
import path from 'node:path'

const here = path.dirname(new URL(import.meta.url).pathname)
const { PRESET_CSS, PRESET_JS } = await import(path.join(here, 'ui.js'))
// A JSON module import resolves to a namespace whose only export is `default`,
// so destructuring `{ name }` here yields undefined — which is exactly how this
// file once shipped `id: undefined`.
const { default: pkg } = await import(path.join(here, 'package.json'), { with: { type: 'json' } })
const name = pkg.name
if (typeof name !== 'string' || name === '') throw new Error('build.mjs: package.json has no name')

const wrapper = `/**
 * dsh-preset-inspector — browser half (generated by build.mjs from ui.js).
 *
 * Registers with the Web UI's module loader, which is what a plugin's
 * \`exports["./client"]\` entry is fetched through. No React, no bundler: the
 * panel is plain DOM, so it cannot disturb the app's own tree.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports

    var CSS = ${JSON.stringify(PRESET_CSS)}
    var UI = ${JSON.stringify(PRESET_JS)}

    var mounted = false

    function injectStyle() {
      if (document.querySelector('style[data-pi-style]')) return
      var style = document.createElement('style')
      style.setAttribute('data-pi-style', '')
      style.textContent = CSS
      document.head.appendChild(style)
    }

    function runUi() {
      if (mounted) return
      mounted = true
      injectStyle()
      try {
        // The IIFE is self-contained: it finds window.__dshPresets, mounts the
        // launcher, and renders on demand.
        new Function(UI)()
      } catch (error) {
        console.warn('[dsh-preset-inspector] panel failed to start:', error)
      }
    }

    function apply(ctx) {
      if (typeof document === 'undefined') return
      if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', runUi)
      else runUi()
      if (ctx && typeof ctx.effect === 'function') {
        ctx.effect(() => () => {
          mounted = false
          var launcher = document.querySelector('[data-pi-launcher]')
          var overlay = document.querySelector('[data-pi-overlay]')
          var style = document.querySelector('style[data-pi-style]')
          if (overlay) overlay.remove()
          if (launcher) launcher.remove()
          if (style) style.remove()
        }, 'preset-inspector.client')
      }
    }

    exports.apply = apply
    exports.inject = []
    return module.exports
  },
})
`

const outPath = path.join(here, 'lib', 'client.js')
fs.mkdirSync(path.dirname(outPath), { recursive: true })

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
  if (current !== wrapper) {
    console.error('lib/client.js is stale — run: node build.mjs')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
  process.exit(0)
}

fs.writeFileSync(outPath, wrapper)
console.log(`wrote ${path.relative(here, outPath)} (${wrapper.length} bytes)`)
